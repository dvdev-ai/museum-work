def patch_slide(path: str):
    with open(path, 'r', encoding='utf-8') as f:
        data = f.read()

    # Stage 1: replace originals with temp tokens
    for orig, tmp in TEMP.items():
        data = data.replace(f'srgbClr val="{orig}"', f'srgbClr val="{tmp}"')

    # Stage 2: replace temp tokens with final values
    for tmp, fin in FINAL.items():
        data = data.replace(f'srgbClr val="{tmp}"', f'srgbClr val="{fin}"')

    # Expand titles. Titles appear in <a:t>...</a:t> within bold black runs.
    # A title may be split across multiple runs (e.g. "Г" + "аечн" + "ый" + " " + "ключ").
    # Approach: for each entry in TITLE_EXPANSIONS, find a sequence of <a:r>...</a:r> runs
    # whose concatenated text equals the source title, then collapse them into a single run
    # with the expanded title text.

    # We will operate per <p:txBody>: identify runs sequentially in document order.
    # First, do simple <a:t>SRC</a:t> replacement (single-run case).
    for src, dst in TITLE_EXPANSIONS.items():
        single = f'<a:t>{src}</a:t>'
        if single in data:
            data = data.replace(single, f'<a:t>{dst}</a:t>')

    # Multi-run case: per <a:p> paragraph, if concatenated text in runs equals src, collapse.
    def collapse_paragraph(p_xml: str) -> str:
        # Collect all <a:r>...</a:r> in order.
        runs = re.findall(r'<a:r>(.*?)</a:r>', p_xml, flags=re.DOTALL)
        if not runs:
            return p_xml
        texts = []
        rprs = []
        for r in runs:
            tm = re.search(r'<a:t>([^<]*)</a:t>', r)
            pm = re.search(r'<a:rPr[^>]*?/>|<a:rPr(?:\s[^>]*)?>.*?</a:rPr>', r, flags=re.DOTALL)
            if not tm:
                return p_xml
            texts.append(tm.group(1))
            rprs.append(pm.group(0) if pm else '')
        joined = ''.join(texts)
        # Try exact match, then trimmed/normalized.
        match_key = None
        for cand in (joined, joined.rstrip(), joined.strip(), joined.replace('\xa0', ' ')):
            if cand in TITLE_EXPANSIONS:
                match_key = cand
                break
        if match_key is not None:
            new_text = TITLE_EXPANSIONS[match_key]
            # Use first run's rPr; ensure no err markings; ensure no dirty.
            base_rpr = rprs[0]
            # Strip err="1" markers
            base_rpr = re.sub(r'\s+err="\d"', '', base_rpr)
            # Strip lang="..."
            base_rpr = re.sub(r'\s+lang="[^"]+"', '', base_rpr)
            # Strip dirty
            base_rpr = re.sub(r'\s+dirty="\d"', '', base_rpr)
            new_run = f'<a:r>{base_rpr}<a:t>{new_text}</a:t></a:r>'
            # Replace all <a:r>...</a:r> in p_xml with new_run (single)
            # Need to remove all <a:r>...</a:r> entries.
            # Simplest: replace whole runs sequence.
            new_p_xml = re.sub(r'(<a:r>.*?</a:r>)+', new_run, p_xml, count=1, flags=re.DOTALL)
            return new_p_xml
        return p_xml

    def patch_paragraphs(xml: str) -> str:
        # Find <a:p>...</a:p> blocks and process each.
        return re.sub(r'<a:p>(.*?)</a:p>', lambda m: '<a:p>' + collapse_paragraph(m.group(1)) + '</a:p>', xml, flags=re.DOTALL)

    data = patch_paragraphs(data)

    with open(path, 'w', encoding='utf-8') as f:
        f.write(data)


slides_dir = os.path.join(OUT_DIR, 'ppt', 'slides')
for fname in sorted(os.listdir(slides_dir)):
    if fname.startswith('slide') and fname.endswith('.xml'):
        patch_slide(os.path.join(slides_dir, fname))

# Repack into pptx
if os.path.exists(OUT_PPTX):
    os.remove(OUT_PPTX)
with zipfile.ZipFile(OUT_PPTX, 'w', zipfile.ZIP_DEFLATED) as zout:
    for root, _, files in os.walk(OUT_DIR):
        for fn in files:
            fp = os.path.join(root, fn)
            rel = os.path.relpath(fp, OUT_DIR)
            zout.write(fp, rel)

print(f"OK -> {OUT_PPTX}")
print("Size:", os.path.getsize(OUT_PPTX), "bytes")
