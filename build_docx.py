def parse_int(s):
    m = re.search(r'\d+', s or '')
    return int(m.group(0)) if m else 1


def extract_items():
    items = []  # list of dicts: title, aff, qty (int), location, slide
    files = sorted(glob.glob(os.path.join(SLIDES_DIR, 'slide*.xml')),
                   key=lambda x: int(re.search(r'\d+', os.path.basename(x)).group()))
    for f in files:
        n = int(re.search(r'\d+', os.path.basename(f)).group())
        if n < 11:
            continue
        with open(f, 'r', encoding='utf-8') as fp:
            data = fp.read()

        sp_pattern = re.compile(r'<p:sp>(.*?)</p:sp>', re.DOTALL)
        cur = {'title': '', 'aff': '', 'qty': '', 'label': '', 'slide': n}
        for sp in sp_pattern.findall(data):
            texts = re.findall(r'<a:t>([^<]*)</a:t>', sp)
            joined = ''.join(texts)
            if joined.startswith('Принадлежность: '):
                cur['aff'] = joined.replace('Принадлежность: ', '')
            elif joined.startswith('Кол-во'):
                cur['qty'] = joined
            elif 'sz="800"' in sp and 'b="1"' in sp and re.match(r'^[ЛП]\d+(?:[,\s]+[ЛП]?\d+)*$', joined.strip()):
                cur['label'] = joined.strip()
                if cur['title'] or cur['aff']:
                    items.append(cur)
                cur = {'title': '', 'aff': '', 'qty': '', 'label': '', 'slide': n}
            else:
                # Title detection: bold text in size 1000-1200 (title range) — explicit black color OR inherited
                if re.search(r'sz="1[012]00"[^>]*b="1"', sp) or re.search(r'b="1"[^>]*sz="1[012]00"', sp):
                    # Exclude shape labels like ВИТРИНЫ, ОПИСЬ, СОДЕРЖАНИЕ, MUSEUM HEADER
                    skips = ('ОПИСЬ', 'ВИТРИН', 'СОДЕРЖАНИЕ', 'МУЗЕЙ', 'СамРО')
                    if joined and not any(joined.startswith(s) for s in skips) and len(joined) < 250 and 'СТЕЛЛАЖИ' not in joined:
                        cur['title'] = joined.strip()
    return items


def shade(cell, hex_color):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_color)
    tc_pr.append(shd)


