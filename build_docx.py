    p = doc.add_paragraph()
    p.add_run('Принимающая сторона: ').bold = True
    p.add_run('___________________________________________________________________________')

    doc.add_paragraph()

    # Heading
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run('ОПИСЬ ПРЕДМЕТОВ')
    r.bold = True
    r.font.size = Pt(14)

    # Table
    table = doc.add_table(rows=1, cols=6)
