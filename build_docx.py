    # Totals
    p = doc.add_paragraph()
    r = p.add_run(f'Всего наименований (позиций): {len(items)}.')
    r.bold = True
    r.font.size = Pt(12)
    p = doc.add_paragraph()
    r = p.add_run(f'Всего единиц хранения: {total_qty} шт.')
    r.bold = True
    r.font.size = Pt(12)

    doc.add_paragraph()

